  KEY `channel_authorizations_valid_idx` (`valid_from`, `valid_to`),
  KEY `channel_authorizations_status_idx` (`status`)
) DEFAULT CHARACTER SET utf8mb4 COLLATE utf8mb4_unicode_ci;

