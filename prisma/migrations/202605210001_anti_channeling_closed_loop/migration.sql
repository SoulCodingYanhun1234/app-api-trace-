CREATE TABLE IF NOT EXISTS `channel_authorizations` (
  `id` INT NOT NULL AUTO_INCREMENT,
  `agent_id` INT NULL,
  `agent_code` VARCHAR(64) NULL,
  `agent_name` VARCHAR(128) NULL,
  `channel_type` VARCHAR(64) NULL,
  `channel_level` VARCHAR(64) NULL,
  `province_name` VARCHAR(64) NULL,
  `city_name` VARCHAR(64) NULL,
  `district_name` VARCHAR(64) NULL,
  `region_group` VARCHAR(255) NULL,
  `valid_from` DATE NULL,
  `valid_to` DATE NULL,
  `approval_status` VARCHAR(64) NULL DEFAULT 'active',
  `allow_online` TINYINT(1) NOT NULL DEFAULT 0,
  `allow_wholesale` TINYINT(1) NOT NULL DEFAULT 0,
  `rules` JSON NULL,
  `status` INT NOT NULL DEFAULT 1,
  `remark` VARCHAR(255) NULL,
